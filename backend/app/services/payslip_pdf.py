import calendar
from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from app.models.payroll import RunStatus

CURRENCY = "PKR"
BOLD_ROWS = {"Gross salary", "Net pay"}


def money_text(value) -> str:
    return f"{CURRENCY} {value:,.2f}"


def payslip_sections(slip) -> list[tuple[str, list[tuple[str, str]]]]:
    """The text of the payslip as (section title, [(label, value), ...]). Kept separate from the drawing so it is easy to test."""
    return [
        ("Employee", [
            ("Name", slip.full_name),
            ("Employee code", slip.employee_code),
            ("Department", slip.department_name),
            ("Designation", slip.designation_name),
        ]),
        ("Salary structure (monthly)", [
            ("Basic salary", money_text(slip.basic)),
            ("House rent allowance (40%)", money_text(slip.hra)),
            ("Medical allowance (10%)", money_text(slip.medical)),
            ("Gross salary", money_text(slip.gross_salary)),
        ]),
        ("Attendance", [
            ("Working days in the month", str(slip.working_days)),
            ("Working days employed", str(slip.payable_days)),
            ("Absent days", str(slip.absent_days)),
            ("Unpaid leave days", str(slip.unpaid_days)),
            ("Half days", str(slip.half_days)),
            ("Deduction days", f"{slip.deduction_days:g}"),
        ]),
        ("Pay", [
            ("Gross for the days employed", money_text(slip.prorated_gross)),
            ("Deduction for absence, unpaid leave and half days", money_text(slip.attendance_deduction)),
            ("Income tax", money_text(slip.tax)),
            ("Net pay", money_text(slip.net_pay)),
        ]),
    ]


def build_payslip_pdf(slip, company_name: str) -> bytes:
    run = slip.run
    period = f"{calendar.month_name[run.month]} {run.year}"

    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4, pageCompression=0)
    pdf.setTitle(f"Payslip {slip.employee_code} {period}")
    width, height = A4
    left, right = 50, width - 50
    y = height - 60

    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(left, y, company_name)
    y -= 24
    pdf.setFont("Helvetica", 12)
    pdf.drawString(left, y, f"Payslip for {period}")
    if run.status != RunStatus.finalized:
        y -= 18
        pdf.setFillColorRGB(0.75, 0.1, 0.1)
        pdf.setFont("Helvetica-Bold", 10)
        pdf.drawString(left, y, "DRAFT - not final, the figures may still change")
        pdf.setFillColorRGB(0, 0, 0)
    y -= 14
    pdf.line(left, y, right, y)
    y -= 24

    for title, rows in payslip_sections(slip):
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(left, y, title)
        y -= 16
        for label, value in rows:
            pdf.setFont("Helvetica-Bold" if label in BOLD_ROWS else "Helvetica", 10)
            pdf.drawString(left + 8, y, label)
            pdf.drawRightString(right, y, value)
            y -= 15
        y -= 10

    pdf.setFont("Helvetica", 8)
    pdf.drawString(left, 50, "Tax is worked out on the full monthly gross using the company tax slab. Generated by HCM Lite.")
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()